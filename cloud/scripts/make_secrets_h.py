#!/usr/bin/env python3
"""Write firmware/hat/secrets.h for one hat from cloud/certs/ and cloud/.env.

    python3 cloud/scripts/make_secrets_h.py W01 --ssid "MyHotspot" --password "secret"

The output holds the device private key and Wi-Fi password, so it is gitignored.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CERTS = ROOT / "cloud" / "certs"
OUT = ROOT / "firmware" / "hat" / "secrets.h"


def env_value(key: str) -> str:
    env = ROOT / "cloud" / ".env"
    if env.exists():
        for line in env.read_text().splitlines():
            if line.startswith(f"{key}="):
                return line.split("=", 1)[1].strip().strip('"').strip("'")
    raise SystemExit(f"{key} not found in cloud/.env")


def c_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def pem_literal(name: str, path: Path) -> str:
    if not path.exists():
        raise SystemExit(f"missing {path.relative_to(ROOT)}")
    pem = path.read_text().strip()
    if not pem.startswith("-----BEGIN"):
        raise SystemExit(f"{path.name} is not a PEM file")
    return f'static const char {name}[] PROGMEM = R"PEM(\n{pem}\n)PEM";\n'


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("worker_id", help="thing name, e.g. W01")
    ap.add_argument("--ssid", required=True, help="2.4 GHz Wi-Fi name (phone hotspot works)")
    ap.add_argument("--password", required=True)
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args()

    wid = args.worker_id
    if not re.fullmatch(r"W\d{2,3}", wid):
        raise SystemExit("worker_id must look like W01")
    endpoint = env_value("IOT_ENDPOINT").removeprefix("https://")

    body = (
        "// Generated by cloud/scripts/make_secrets_h.py. Do not commit (gitignored).\n"
        "#pragma once\n\n"
        f"#define WORKER_ID {c_string(wid)}\n"
        f"#define WIFI_SSID {c_string(args.ssid)}\n"
        f"#define WIFI_PASSWORD {c_string(args.password)}\n"
        f"#define AWS_IOT_ENDPOINT {c_string(endpoint)}\n"
        "#define AWS_IOT_PORT 8883\n\n"
        + pem_literal("AWS_ROOT_CA", CERTS / "AmazonRootCA1.pem") + "\n"
        + pem_literal("DEVICE_CERT", CERTS / f"{wid}.cert.pem") + "\n"
        + pem_literal("DEVICE_KEY", CERTS / f"{wid}.private.key")
    )
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(body)
    out.chmod(0o600)
    print(f"wrote {out} for {wid} -> {endpoint}")


if __name__ == "__main__":
    main()
